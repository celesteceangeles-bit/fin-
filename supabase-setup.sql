-- Crea las tablas, permisos y función para consultar el estado sin exponer datos privados.

create table if not exists public.solicitudes (
  id bigint generated by default as identity primary key,
  nombre text not null,
  email text not null,
  mascota text not null,
  motivo text not null,
  estado text not null default 'Pendiente' check (estado in ('Pendiente', 'Aprobada', 'Rechazada')),
  mensajes jsonb not null default '[]'::jsonb,
  creado timestamptz not null default now()
);

create table if not exists public.administradores (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  creado timestamptz not null default now()
);

-- Compatibilidad con la tabla administradores creada por la versión anterior.
alter table public.administradores
  add column if not exists user_id uuid references auth.users(id) on delete cascade;
create unique index if not exists administradores_user_id_uidx
  on public.administradores(user_id) where user_id is not null;

alter table public.solicitudes enable row level security;
alter table public.administradores enable row level security;

-- Limpiar políticas anteriores para que el script pueda volver a ejecutarse sin duplicarlas.
drop policy if exists "publica puede enviar solicitudes" on public.solicitudes;
drop policy if exists "administradores pueden leer solicitudes" on public.solicitudes;
drop policy if exists "administradores pueden actualizar solicitudes" on public.solicitudes;
drop policy if exists "administrador puede ver su registro" on public.administradores;

create policy "publica puede enviar solicitudes"
on public.solicitudes for insert to anon, authenticated
with check (
  length(trim(nombre)) > 0 and length(trim(email)) > 3
  and length(trim(mascota)) > 0 and length(trim(motivo)) > 0
  and estado = 'Pendiente' and mensajes = '[]'::jsonb
);

create policy "administradores pueden leer solicitudes"
on public.solicitudes for select to authenticated
using (exists (select 1 from public.administradores a where a.user_id = auth.uid()));

create policy "administradores pueden actualizar solicitudes"
on public.solicitudes for update to authenticated
using (exists (select 1 from public.administradores a where a.user_id = auth.uid()))
with check (exists (select 1 from public.administradores a where a.user_id = auth.uid()));

create policy "administrador puede ver su registro"
on public.administradores for select to authenticated
using (user_id = auth.uid());

create or replace function public.crear_solicitud(p_nombre text, p_email text, p_mascota text, p_motivo text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare nuevo_id bigint;
begin
  if length(trim(coalesce(p_nombre,''))) = 0
     or length(trim(coalesce(p_email,''))) < 4
     or length(trim(coalesce(p_mascota,''))) = 0
     or length(trim(coalesce(p_motivo,''))) = 0 then
    raise exception 'Completá todos los campos con datos válidos.';
  end if;
  insert into public.solicitudes(nombre,email,mascota,motivo,estado,mensajes)
  values (trim(p_nombre),lower(trim(p_email)),trim(p_mascota),trim(p_motivo),'Pendiente','[]'::jsonb)
  returning id into nuevo_id;
  return nuevo_id;
end;
$$;

revoke all on function public.crear_solicitud(text,text,text,text) from public;
grant execute on function public.crear_solicitud(text,text,text,text) to anon, authenticated;

create or replace function public.consultar_estado_solicitud(p_id bigint, p_email text)
returns table(id bigint, mascota text, estado text)
language sql
security definer
set search_path = public
stable
as $$
  select s.id, s.mascota, s.estado
  from public.solicitudes s
  where s.id = p_id and lower(s.email) = lower(trim(p_email))
  limit 1;
$$;

revoke all on function public.consultar_estado_solicitud(bigint, text) from public;
grant execute on function public.consultar_estado_solicitud(bigint, text) to anon, authenticated;
grant usage on schema public to anon, authenticated;
grant select, update on public.solicitudes to authenticated;
grant select on public.administradores to authenticated;
